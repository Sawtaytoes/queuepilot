import { afterEach, expect, it, vi } from 'vitest';
vi.mock('./mqttc.js', () => ({ lastState: () => null, recordDeviceNowPlaying: vi.fn() }));
vi.mock('./playback.js', () => ({ currentSession: vi.fn() }));
import { startDeviceNowPlaying } from './deviceNowPlaying.js';
import type { Device } from './types.js';
const device: Device = { id: 'den', name: 'Den TV', uri: 'http://192.0.2.31:32500', mode: 'client', default: false, machineIdentifier: 'den-player' };
afterEach(() => { vi.useRealTimers(); });
it('polls only the selected configured player, reports seconds, and stops cleanly', async () => {
  vi.useFakeTimers();
  let active: string | null = null;
  const read = vi.fn(async () => ({ ratingKey: '123', state: 'paused', viewOffset: 12000, duration: 90000, title: 'Test episode' }));
  const publish = vi.fn();
  const stop = startDeviceNowPlaying({ targets: [device], active: () => active, read, publish });
  await vi.advanceTimersByTimeAsync(1500);
  expect(read).not.toHaveBeenCalled();
  active = 'den';
  await vi.advanceTimersByTimeAsync(1500);
  expect(read).toHaveBeenCalledWith(device);
  expect(publish).toHaveBeenLastCalledWith('den', expect.objectContaining({ state: 'paused', position: 12, duration: 90, deviceId: 'den' }));
  stop();
  const calls = read.mock.calls.length;
  await vi.advanceTimersByTimeAsync(10000);
  expect(read).toHaveBeenCalledTimes(calls);
});
it('discards a late reading after switching devices and does not turn read failures into idle', async () => {
  vi.useFakeTimers();
  let active: string | null = 'den';
  let resolve!: (v: null) => void;
  const read = vi.fn(() => new Promise<null>((r) => { resolve = r; }));
  const publish = vi.fn();
  const stop = startDeviceNowPlaying({ targets: [device], active: () => active, read, publish });
  active = 'shield'; resolve(null);
  await vi.advanceTimersByTimeAsync(0);
  expect(publish).not.toHaveBeenCalled();
  stop();
  const fail = startDeviceNowPlaying({ targets: [device], active: () => 'den', read: async () => { throw new Error('offline'); }, publish });
  await vi.advanceTimersByTimeAsync(0);
  expect(publish).not.toHaveBeenCalled();
  fail();
});
